// Skill and project taxonomy — the rows /api/graph/skills-graph and
// /api/graph/projects-graph are built from when Aurora is mocked.
//
// WHY THIS FILE EXISTS. `mockAurora.fetchSkillsGraph` and `fetchProjectsGraph`
// were literally `async () => ({ domains: [], skills: [], people: [],
// personSkillEdges: [] })`. Both endpoints answered 200 with empty arrays, so
// Explore's Skills and Projects views rendered an empty canvas — no error, no
// console warning, nothing to grep for. `docs/mock-floor.md` calls this out as
// the thing a mock must never be: a stub that returns a shape instead of data.
//
// GENERATED FROM `schema/seed.sql`, not written by hand — these are the same
// rows the real cluster is seeded with, so the mock renders the same graph the
// deployed app does. Person ids (`p-001`…) already match `mock/people.ts`.
// Regenerate by re-extracting the four INSERT families below if the seed moves.
//
// Counts (personCount, skillCount, contributorCount) are deliberately NOT
// stored here. The mock-floor contract forbids a fixture exporting a number it
// could have counted from rows it also exports, because the two drift; the
// provider counts them at build time instead.

