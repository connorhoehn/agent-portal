#!/usr/bin/env node
// Generate the reviewed ID-only data migration; never writes to a database.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const manifest = JSON.parse(readFileSync(resolve(root, 'portal/public/avatars/photos/personas.json'), 'utf8'));
const entries = manifest.personas.filter(p => /^(p|u)-[a-z0-9-]+$/.test(p.subjectId));
if (entries.length !== 71 || new Set(entries.map(p => p.subjectId)).size !== entries.length) throw new Error('Review the changed cast before generating a deployment migration');
const literal = value => "'" + value.replaceAll("'", "''") + "'";
function mapping(kind) {
  const rows = entries.filter(p => p.subjectId.startsWith(kind + '-'));
  for (const row of rows) if (row.portraitUrl !== `/avatars/photos/${row.subjectId}.jpg`) throw new Error(`Unexpected portrait path: ${row.subjectId}`);
  return `WITH portraits(id, url) AS (VALUES\n${rows.map(p => `  (${literal(p.subjectId)}, ${literal(p.portraitUrl)})`).join(',\n')}\n)`;
}
function eligible(table) {
  return `target.id = portraits.id\n  ${table === 'app_users' ? 'AND target.person_id IS NULL\n  ' : ''}AND (target.avatar_url IS NULL OR target.avatar_url = ''\n    OR target.avatar_url IN ('/avatars/' || portraits.id || '.png', '/avatars/' || portraits.id || '.svg'))`;
}
const header = '-- Generated by scripts/avatars/prepare-backfill.mjs from the reviewed portrait manifest.\n-- ID-only: preserve custom photos, linked account photos and unknown identities.\n-- Verify deployed JPG hashes before using schema.migrate plan / approve / apply.\n-- Assessment contributors have no canonical IDs: deliberately excluded.\n';
const update = ['people', 'app_users'].map((table, i) => `${mapping(i ? 'u' : 'p')}\nUPDATE ${table} AS target SET avatar_url = portraits.url${i ? '' : ', updated_at = NOW()'}\nFROM portraits WHERE ${eligible(table)};`).join('\n\n');
// A single query is required by the migration runner's dry-run protocol.
const dry = ['people', 'app_users'].map((table, i) => `SELECT '${table}' AS name, count(*)::bigint AS rows FROM (\n${mapping(i ? 'u' : 'p')}\nSELECT target.id FROM ${table} AS target JOIN portraits ON ${eligible(table)}\n) AS eligible_${table}`).join('\nUNION ALL\n') + ';';
for (const [suffix, body] of [['sql', update], ['dry-run.sql', dry]]) {
  const path = resolve(root, `schema/migrations/2026-11-02-canonical-portraits.${suffix}`);
  const expected = header + body + '\n';
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== expected) throw new Error(`${path} differs from the reviewed cast`);
  } else writeFileSync(path, expected);
}
console.log(`Canonical portrait migration: ${entries.length} IDs (59 people, 12 unlinked accounts); no database writes.`);
