#!/usr/bin/env node
// Pack the seeded runbook bundles (middleware/src/mock/runbook-bundles/<id>/{scripts,data}/…)
// into middleware/src/mock/runbook-bundles.generated.ts, the module the mock seed
// imports (the middleware's jest runs as CommonJS, so the mock cannot read the
// files beside itself through import.meta.url). The real files stay the source:
// edit them, run them, then re-pack. `--check` fails when the module is stale
// (the bundle test runs the same comparison).
//
//   node scripts/runbooks/pack-bundles.mjs [--check]
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('../../', import.meta.url).pathname;
const dir = join(root, 'middleware/src/mock/runbook-bundles');
const out = join(root, 'middleware/src/mock/runbook-bundles.generated.ts');

function walk(d) {
  return readdirSync(d).sort().flatMap((n) => {
    const p = join(d, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const bundles = {};
for (const id of readdirSync(dir).sort()) {
  const base = join(dir, id);
  if (!statSync(base).isDirectory()) continue;
  bundles[id] = walk(base).map((p) => {
    const path = relative(base, p);
    return { path, content: readFileSync(p, 'utf8'), mode: path.startsWith('scripts/') ? '755' : '644' };
  });
}

const text = [
  '// GENERATED by scripts/runbooks/pack-bundles.mjs from mock/runbook-bundles/ — do not edit; edit the files and re-pack.',
  "export const BUNDLE_FILES: Record<string, Array<{ path: string; content: string; mode: '644' | '755' }>> = " + JSON.stringify(bundles, null, 2) + ';',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== text) { console.error('runbook-bundles.generated.ts is stale: node scripts/runbooks/pack-bundles.mjs'); process.exit(1); }
  console.log('runbook bundles packed and current');
} else {
  writeFileSync(out, text);
  console.log(`packed ${Object.keys(bundles).length} bundles → ${relative(root, out)}`);
}
