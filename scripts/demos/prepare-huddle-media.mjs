#!/usr/bin/env node
// Turn exported speaking MP4s into synchronized per-person recordings and
// Chromium fake-camera/fake-microphone inputs for the REAL local call stack.
// All subprocess arguments are arrays; no shell interpolation or network.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertSpeakingReview, hash, makeMediaContract, safeId } from './huddle-media-contract.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const args = process.argv.slice(2);
const option = (key, fallback) => {
  const at = args.indexOf(key);
  if (at < 0) return fallback;
  if (!args[at + 1] || args[at + 1].startsWith('--')) throw new Error(`${key} needs a value`);
  return args[at + 1];
};
const storyboard = resolve(option('--storyboard', join(root, 'docs/demos/work-huddles/storyboard.json')));
const clips = option('--clips', null);
const output = resolve(option('--out', '/private/tmp/work-huddle-media'));
const requestedScene = option('--scene', null);
const reviewFile = option('--review', null);
const validateOnly = args.includes('--validate');
const rate = 12;
const run = (command, argv, stream = 'stdout') => {
  const result = spawnSync(command, argv, { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} failed: ${result.stderr?.trim() || result.status}`);
  return result[stream];
};
const probe = file => JSON.parse(run('ffprobe', ['-v', 'error', '-show_format', '-show_streams', '-of', 'json', file]));
const requireAudioSignal = file => {
  const volume = run('ffmpeg', ['-nostdin', '-hide_banner', '-nostats', '-i', file, '-map', '0:a:0',
    '-af', 'volumedetect', '-vn', '-sn', '-dn', '-f', 'null', '-'], 'stderr');
  const peak = volume.match(/max_volume:\s*(-?[\d.]+|-inf)\s*dB/);
  // An audio track containing silence passed the old stream-only check.
  // This proves a usable signal; exact speech and lip sync still need review.
  const peakDb = peak ? Number(peak[1]) : NaN;
  if (!Number.isFinite(peakDb) || peakDb < -55) throw new Error(`Speaking audio is silent or too quiet (peak must be at least -55 dBFS): ${file}`);
};
const ticks = seconds => Math.ceil(seconds * rate) / rate;
// Preserve the full webcam portrait. A square source cropped to widescreen
// removed hair and shoulders; a blurred duplicate fills only the side bars.
const videoFilter = `split=2[backdrop][portrait];[backdrop]scale=480:270:force_original_aspect_ratio=increase,crop=480:270,gblur=sigma=18[blurred];[portrait]scale=480:270:force_original_aspect_ratio=decrease:force_divisible_by=2[face];[blurred][face]overlay=(W-w)/2:(H-h)/2,fps=${rate},setsar=1,format=yuv420p`;
// Encoding AAC in every segment adds encoder padding at every boundary. Keep
// intermediates as PCM with precise NUT timestamps; encode AAC only once.
const common = ['-c:v', 'libx264', '-preset', 'ultrafast', '-crf', '23', '-c:a', 'pcm_s16le', '-ar', '48000', '-ac', '2'];
const boundedAudio = seconds => `apad,atrim=end_sample=${Math.round(seconds * 48000)},asetpts=N/SR/TB`;

try {
  const story = JSON.parse(readFileSync(storyboard, 'utf8'));
  const contract = makeMediaContract(story, root);
  if (!clips) throw new Error('Provide --clips /absolute/path/to/exported-speaking-MP4s. No speaking video has been generated by this script.');
  const clipRoot = resolve(clips);
  const cast = story.cast;
  if (!Array.isArray(cast) || cast.length < 2 || new Set(cast.map(a => a.userId)).size !== cast.length || cast.some(a => !safeId(a.userId))) throw new Error('The storyboard needs at least two distinct safe actor IDs.');
  for (const actor of cast) if (!existsSync(resolve(root, actor.portrait))) throw new Error(`Missing portrait for ${actor.name}: ${actor.portrait}`);
  const scenes = story.scenes.filter(scene => !requestedScene || scene.id === requestedScene);
  if (!scenes.length) throw new Error(`No scene named ${requestedScene}`);
  const media = new Map();
  const missing = [];
  for (const scene of scenes) {
    if (!safeId(scene.id) || !Number.isFinite(scene.startHoldSeconds) || scene.startHoldSeconds < 0) throw new Error('Invalid scene ID or opening hold.');
    for (const turn of scene.turns) {
      if (!safeId(turn.id) || !cast.some(a => a.userId === turn.actor) || turn.clip !== `${turn.id}.mp4`
        || !Number.isFinite(turn.holdAfterSeconds) || turn.holdAfterSeconds < 0) throw new Error(`Invalid turn: ${turn.id}`);
      const file = join(clipRoot, turn.clip);
      if (!existsSync(file)) { missing.push(file); continue; }
      const info = probe(file);
      const seconds = Number(info.format?.duration);
      if (!info.streams.some(s => s.codec_type === 'audio') || !info.streams.some(s => s.codec_type === 'video') || !Number.isFinite(seconds) || seconds <= 0 || seconds > 120) throw new Error(`A speaking clip needs video, audible audio and a duration up to 120s: ${file}`);
      requireAudioSignal(file);
      media.set(turn.id, { file, seconds: ticks(seconds) });
    }
  }
  if (missing.length) throw new Error(`Speaking clips still needed (${missing.length}):\n${missing.join('\n')}`);
  if (reviewFile) assertSpeakingReview(JSON.parse(readFileSync(resolve(reviewFile), 'utf8')), contract, media);
  const verification = {
    kind: 'assembled-media-verification', contentSha256: contract.contentSha256,
    technicalChecks: 'passed', speakingReview: reviewFile ? 'verified-against-clip-bytes' : 'unverified',
    clips: [...media].map(([id, source]) => ({ id, clipSha256: hash(readFileSync(source.file)), durationSeconds: source.seconds })),
    limits: ['Exact words, identity and lip sync require watching and listening to the exported clips.',
      'Capture synchronization must be checked when the two device previews begin.'],
  };
  if (validateOnly) {
    console.log(`Technical checks passed: ${media.size} clips, ${cast.length} actors, ${scenes.length} scenes. Speaking review: ${verification.speakingReview}.`);
    process.exit(0);
  }
  mkdirSync(output, { recursive: true });
  writeFileSync(join(output, 'media-verification.json'), JSON.stringify(verification, null, 2) + '\n');
  for (const scene of scenes) {
    let cursor = ticks(scene.startHoldSeconds);
    const timeline = scene.turns.map(turn => {
      const entry = { id: turn.id, actor: turn.actor, atSeconds: cursor, speechSeconds: media.get(turn.id).seconds, action: turn.action, holdAfterSeconds: ticks(turn.holdAfterSeconds) };
      cursor += entry.speechSeconds + entry.holdAfterSeconds;
      return entry;
    });
    const sceneOut = join(output, scene.id);
    mkdirSync(sceneOut, { recursive: true });
    writeFileSync(join(sceneOut, 'timeline.json'), JSON.stringify({ scene: scene.id, durationSeconds: cursor,
      framesPerSecond: rate, speakingReview: verification.speakingReview, contentSha256: contract.contentSha256, timeline }, null, 2) + '\n');
    for (const actor of cast) {
      const work = mkdtempSync(join(sceneOut, `${actor.userId}-segments-`));
      const portrait = resolve(root, actor.portrait);
      const files = [];
      const segment = (seconds, speaking) => {
        if (!seconds) return;
        const name = `segment-${String(files.length).padStart(3, '0')}.nut`;
        const input = speaking ? ['-i', speaking] : ['-loop', '1', '-i', portrait, '-f', 'lavfi', '-i', 'anullsrc=r=48000:cl=stereo'];
        run('ffmpeg', ['-nostdin', '-hide_banner', '-loglevel', 'error', '-y', ...input, '-t', String(seconds),
          '-vf', `${videoFilter},tpad=stop_mode=clone:stop_duration=2`, '-frames:v', String(Math.round(seconds * rate)),
          '-af', boundedAudio(seconds), ...common, join(work, name)]);
        files.push(name);
      };
      segment(ticks(scene.startHoldSeconds), null);
      for (const turn of scene.turns) {
        const source = media.get(turn.id);
        segment(source.seconds, turn.actor === actor.userId ? source.file : null);
        segment(ticks(turn.holdAfterSeconds), null);
      }
      const list = join(work, 'concat.txt');
      writeFileSync(list, files.map(name => `file '${name}'`).join('\n') + '\n');
      const replay = join(sceneOut, `${actor.userId}.mp4`);
      run('ffmpeg', ['-nostdin', '-hide_banner', '-loglevel', 'error', '-y', '-f', 'concat', '-safe', '0', '-i', list,
        '-c:v', 'copy', '-af', boundedAudio(cursor), '-c:a', 'aac', '-ar', '48000', '-ac', '2', '-movflags', '+faststart', replay]);
      const camera = join(sceneOut, `${actor.userId}.y4m`);
      const microphone = join(sceneOut, `${actor.userId}.wav`);
      run('ffmpeg', ['-nostdin', '-hide_banner', '-loglevel', 'error', '-y', '-i', replay,
        '-frames:v', String(Math.round(cursor * rate)), '-an', '-pix_fmt', 'yuv420p', '-f', 'yuv4mpegpipe', camera]);
      run('ffmpeg', ['-nostdin', '-hide_banner', '-loglevel', 'error', '-y', '-i', replay, '-vn',
        '-af', boundedAudio(cursor), '-ar', '48000', '-ac', '1', '-c:a', 'pcm_s16le', microphone]);
      const flags = [
        `--user-data-dir=/private/tmp/work-huddle-${scene.id}-${actor.userId}`,
        '--use-fake-device-for-media-stream',
        `--use-file-for-fake-video-capture=${camera}`,
        `--use-file-for-fake-audio-capture=${microphone}`,
        '--autoplay-policy=no-user-gesture-required',
        `http://localhost:5183/workspaces`,
      ];
      writeFileSync(join(sceneOut, `${actor.userId}-chrome-args.json`), JSON.stringify(flags, null, 2) + '\n');
      console.log(`${scene.id} · ${actor.name}: ${replay}\n  camera ${camera}\n  microphone ${microphone}`);
    }
  }
  console.log('Media prepared. Launch separate Chromium processes with each generated args file, sign in as the matching actor, and rehearse against timeline.json. Device preview can start playback before Join; open both checks together and verify that the first lines align within the opening hold.');
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
