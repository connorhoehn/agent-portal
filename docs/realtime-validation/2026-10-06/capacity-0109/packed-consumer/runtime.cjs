const server = require('@connorhoehn/realtime-modules/server');
const call = require('@connorhoehn/realtime-modules/call');
const assert = require('assert');
assert.equal(call.dmLobbyPrefix({ prefix: 'social:' }), 'social:dm:');
assert.deepEqual(call.parseDmLobby('social:dm:a:b', { prefix: 'social:' }), { kind: 'dm', prefix: 'social:', members: ['a', 'b'] });
assert.deepEqual(call.parseDmLobby('dmg:h'), { kind: 'dmg', prefix: '', hash: 'h' });
assert.equal(call.parseDmLobby('orgiq:dm:a:b', { prefix: 'social:' }), null);
(async () => {
  const asks = [];
  const router = new server.LocalRealtimeRouter({ publishProofMaxAgeMs: 2000, authorize: ({ kind, clientId }) => { asks.push(kind + ':' + clientId); return Promise.resolve(true); } });
  const ctx = { userId: 'a' };
  router._setHandle({ getClientContext: id => id === 'a' ? ctx : null, sendToClient: () => true, listClients: () => ['a'] });
  const scope = server.createAuthorityScope('chat.send');
  for (let i = 0; i < 3; i++) assert.equal(await router.checkChannel('publish', 'a', 'room', { scope, silent: true }), true);
  assert.deepEqual(asks, ['publish:a']);
  assert.equal(server.revokePublishProofs(scope), 1);
  await router.checkChannel('publish', 'a', 'room', { scope, silent: true });
  assert.deepEqual(asks, ['publish:a', 'publish:a']);
  const off = new server.LocalRealtimeRouter({ authorize: () => { asks.push('off'); return true; } });
  off._setHandle({ getClientContext: () => ctx, sendToClient: () => true, listClients: () => ['a'] });
  await off.checkChannel('publish', 'a', 'room', { scope, silent: true }); await off.checkChannel('publish', 'a', 'room', { scope, silent: true });
  assert.equal(asks.filter(x => x === 'off').length, 2);
  scope.close();
  console.log('packed 0.109.0 runtime: parseDmLobby/dmLobbyPrefix + publish proof share/revoke/off OK');
})().catch(e => { console.error(e); process.exit(1); });
