import { expect, test } from '@playwright/test';
test('composer notices are compact, hover/focus accessible, click-pinned and dismissible', async ({ page }) => {
  await page.route('**/api/**', route => route.abort());
  await page.route('**/__composer-notices', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><html><body><div id="root"></div><script type="module">import RefreshRuntime from "/@react-refresh"; RefreshRuntime.injectIntoGlobalHook(window); window.$RefreshReg$=()=>{}; window.$RefreshSig$=()=>type=>type; window.__vite_plugin_react_preamble_installed__=true;</script><script type="module" src="/e2e/fixtures/composer-advisories.tsx"></script></body></html>' }));
  await page.goto('/__composer-notices');
  const trigger = page.getByRole('button', { name: 'Composer notices (2)' });
  await expect(trigger).toBeVisible();
  const mode = page.getByTestId('notice-composer-mode-pill');
  const refs = page.getByTestId('notice-composer-references');
  expect((await mode.boundingBox())!.x).toBeLessThan((await refs.boundingBox())!.x);
  expect((await refs.boundingBox())!.x).toBeLessThan((await trigger.boundingBox())!.x);
  await expect(page.getByText('Session history unavailable')).toHaveCount(0);
  await trigger.hover();
  const preview = page.getByTestId('composer-notices-preview');
  await expect(preview).toBeVisible();
  await expect(preview.getByRole('listitem')).toHaveCount(2);
  await expect(trigger).not.toBeFocused();
  await page.mouse.move(0, 0);
  await expect(preview).toHaveCount(0);
  await trigger.focus();
  await expect(preview).toBeVisible();
  await trigger.click();
  const panel = page.getByRole('dialog', { name: 'Composer notices' });
  await expect(panel).toBeVisible();
  await page.mouse.move(0, 0);
  await expect(panel.getByRole('listitem')).toHaveCount(2);
  const bounds = await panel.boundingBox();
  expect(bounds!.y).toBeGreaterThanOrEqual(0);
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(900);
  await page.screenshot({ path: test.info().outputPath('composer-notices.png') });
  await page.keyboard.press('Escape');
  await expect(panel).toHaveCount(0);
  await expect(trigger).toBeFocused();
  await page.getByRole('button', { name: 'Resolve notices' }).click();
  await expect(trigger).toHaveCount(0);
});
