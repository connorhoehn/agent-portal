import { test, expect } from './cdpTest';
test.use({ baseURL: 'http://localhost:5183', viewport: { width: 1280, height: 900 }, actionTimeout: 5_000, navigationTimeout: 10_000 });

test('editable shared deck presents selected slide and returns with dirty text and conversation draft intact', async ({ page }) => {
  await page.route('**/__deck-editor-present', route => route.fulfill({ contentType: 'text/html', body: `<!doctype html><html><body><div id="root"></div>
    <script type="module">import RefreshRuntime from '/@react-refresh'; RefreshRuntime.injectIntoGlobalHook(window);
      window.$RefreshReg$ = () => {}; window.$RefreshSig$ = () => type => type; window.__vite_plugin_react_preamble_installed__ = true;
    </script><script type="module" src="/e2e/fixtures/deck-editor-present.tsx"></script></body></html>` }));
  const writes: string[] = [], errors: string[] = [];
  page.on('request', request => { if (request.method() !== 'GET') writes.push(new URL(request.url()).pathname); });
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (/Maximum update depth exceeded/.test(message.text())) errors.push(message.text()); });
  await page.goto('/__deck-editor-present');
  const proof = () => page.evaluate(() => (window as typeof window & { __deckPresentFixture: {
    dirty: boolean; saves: number; agentSubmissions: number; currentSpec: { slides: { id: string; title: string }[] };
    previewSpec: { slides: { id: string; title: string }[] }; savedSpec: unknown;
  } }).__deckPresentFixture);
  const editor = page.getByTestId('fixture-deck-editor');
  const position = page.getByTestId('fixture-deck-editor-position');
  await expect(editor).toBeVisible(); await expect(position).toHaveText('Slide 1 of 3');
  const savedBefore = (await proof()).savedSpec;
  await page.getByTestId('fixture-deck-editor-slide-select-details').click();
  await expect(position).toHaveText('Slide 2 of 3');
  const title = page.getByTestId('fixture-deck-editor-slide-title');
  const editedTitle = 'Unsaved validation title';
  await title.fill(editedTitle);
  await expect(page.getByTestId('fixture-deck-shell')).toContainText('Unsaved changes');
  await expect(page.getByTestId('fixture-deck-save')).toBeEnabled();
  await expect(page.getByTestId('fixture-deck-download')).toBeDisabled();
  await expect.poll(async () => (await proof()).previewSpec?.slides.find(slide => slide.id === 'details')?.title).toBe(editedTitle);
  const input = page.getByTestId('fixture-editor-question-input').locator('[contenteditable="true"]');
  const draft = 'Keep this draft beside my unsaved slide edit.';
  await input.fill(draft);
  const presentButton = page.getByTestId('fixture-deck-editor-toolbar-present');
  await expect(presentButton).toBeVisible(); await presentButton.click();
  const dialog = page.getByRole('dialog', { name: 'Present Editable presentation fixture' });
  await expect(dialog).toBeVisible();
  const present = page.getByTestId('fixture-deck-present');
  await expect(page.getByTestId('fixture-deck-present-position')).toHaveText('Slide 2 of 3');
  await expect(present.getByRole('img', { name: editedTitle, exact: true })).toBeVisible();
  await page.screenshot({ path: test.info().outputPath('editable-present-selected-slide.png') });
  await present.press('End');
  await expect(page.getByTestId('fixture-deck-present-position')).toHaveText('Slide 3 of 3');
  await expect(present.getByRole('img', { name: 'Sources', exact: true })).toBeVisible();
  await present.press('Escape'); await expect(dialog).toHaveCount(0);
  await expect(position).toHaveText('Slide 3 of 3');
  await expect(input).toHaveText(draft); expect((await proof()).dirty).toBe(true);
  await page.getByTestId('fixture-deck-editor-slide-select-details').click();
  await expect(title).toHaveValue(editedTitle);
  await presentButton.click(); await expect(dialog).toBeVisible();
  await expect(page.getByTestId('fixture-deck-present-position')).toHaveText('Slide 2 of 3');
  await dialog.getByRole('button', { name: 'Chat & agent', exact: true }).click();
  await expect(dialog).toHaveCount(0); await expect(input).toBeFocused();
  await expect(input).toHaveText(draft); await expect(title).toHaveValue(editedTitle);
  await expect(position).toHaveText('Slide 2 of 3');
  await expect(page.getByTestId('fixture-deck-save')).toBeEnabled();
  const final = await proof(); expect(final.dirty).toBe(true); expect(final.saves).toBe(0); expect(final.agentSubmissions).toBe(0);
  expect(final.savedSpec).toEqual(savedBefore);
  expect(final.currentSpec.slides.find(slide => slide.id === 'details')?.title).toBe(editedTitle);
  expect(writes).toEqual([]); expect(errors).toEqual([]);
  await page.screenshot({ path: test.info().outputPath('editable-present-returned-draft.png') });
});

test('Present waits for the edited slide image and recovers from preview failure without saving', async ({ page }) => {
  await page.route('**/__deck-editor-present', route => route.fulfill({ contentType: 'text/html', body: `<!doctype html><html><body><div id="root"></div>
    <script type="module">import RefreshRuntime from '/@react-refresh'; RefreshRuntime.injectIntoGlobalHook(window);
      window.$RefreshReg$ = () => {}; window.$RefreshSig$ = () => type => type; window.__vite_plugin_react_preamble_installed__ = true;
    </script><script type="module" src="/e2e/fixtures/deck-editor-present.tsx"></script></body></html>` }));
  const errors: string[] = [], writes: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (/Maximum update depth exceeded/.test(message.text())) errors.push(message.text()); });
  page.on('request', request => { if (request.method() !== 'GET') writes.push(new URL(request.url()).pathname); });
  await page.goto('/__deck-editor-present');
  await expect(page.getByTestId('fixture-deck-editor-stage-image')).toBeVisible();
  await page.getByTestId('fixture-deck-editor-slide-select-details').click();
  const title = page.getByTestId('fixture-deck-editor-slide-title');
  const input = page.getByTestId('fixture-editor-question-input').locator('[contenteditable="true"]');
  const draft = 'Keep this question while the slides render.';
  await input.fill(draft);
  await page.evaluate(() => { (window as any).__deckPresentFixture.delayNextPreview = true; });
  const editedTitle = 'Current unsaved validation';
  await title.fill(editedTitle);
  const presentButton = page.getByTestId('fixture-deck-editor-toolbar-present');
  await presentButton.click();
  const dialog = page.getByRole('dialog', { name: 'Present Editable presentation fixture' });
  await expect(page.getByTestId('fixture-deck-present-loading')).toBeVisible();
  await expect(dialog.getByRole('img')).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => typeof (window as any).__deckPresentFixture.releasePreview)).toBe('function');
  await page.screenshot({ path: test.info().outputPath('editable-present-waits-current-preview.png') });
  await page.evaluate(() => { (window as any).__deckPresentFixture.releasePreview(); });
  const present = page.getByTestId('fixture-deck-present');
  await expect(page.getByTestId('fixture-deck-present-position')).toHaveText('Slide 2 of 3');
  const image = present.getByRole('img', { name: editedTitle, exact: true });
  await expect(image).toBeVisible();
  expect(decodeURIComponent((await image.getAttribute('src'))!)).toContain(editedTitle);
  expect(decodeURIComponent((await image.getAttribute('src'))!)).not.toContain('Validation next');
  await page.getByRole('button', { name: 'Exit presentation', exact: true }).click();
  await expect(title).toHaveValue(editedTitle); await expect(input).toHaveText(draft);
  await page.evaluate(() => { (window as any).__deckPresentFixture.failNextPreview = true; });
  const finalTitle = 'Retry this current validation';
  await title.fill(finalTitle); await presentButton.click();
  await expect(page.getByTestId('fixture-deck-present-error')).toContainText('Fixture render unavailable.');
  await expect(dialog.getByRole('img')).toHaveCount(0);
  await dialog.getByRole('button', { name: 'Retry preview', exact: true }).click();
  const recovered = present.getByRole('img', { name: finalTitle, exact: true });
  await expect(recovered).toBeVisible();
  expect(decodeURIComponent((await recovered.getAttribute('src'))!)).toContain(finalTitle);
  await page.screenshot({ path: test.info().outputPath('editable-present-recovered-current-preview.png') });
  await page.getByRole('button', { name: 'Exit presentation', exact: true }).click();
  await expect(title).toHaveValue(finalTitle); await expect(input).toHaveText(draft);
  await expect(page.getByTestId('fixture-deck-save')).toBeEnabled();
  const proof = await page.evaluate(() => {
    const fixture = (window as any).__deckPresentFixture;
    return { dirty: fixture.dirty, saves: fixture.saves, agentSubmissions: fixture.agentSubmissions, selectedSlide: fixture.selectedSlide };
  });
  expect(proof).toEqual({ dirty: true, saves: 0, agentSubmissions: 0, selectedSlide: 'details' });
  expect(writes).toEqual([]); expect(errors).toEqual([]);
});
