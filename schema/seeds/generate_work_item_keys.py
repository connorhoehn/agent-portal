#!/usr/bin/env python3
"""Reserve immutable work keys, then render the SQL migration and runtime map.

Existing entries are retained even when a seeded item disappears. Never renumber
them: commits and PRs may already refer to them. --check does not write files.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from generate_program_seed import INITIATIVES

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / 'schema/seeds/work_item_keys.json'
RUNTIME = ROOT / 'middleware/src/lib/work-item-keys.ts'
MIGRATION = ROOT / 'schema/work_item_key_schema.sql'
TEMPLATE = ROOT / 'schema/seeds/work_item_key_migration.sql.in'


def outputs():
    data = json.loads(REGISTRY.read_text()) if REGISTRY.exists() else {'version': 1, 'namespaces': {}, 'items': {}}
    prefixes, items = data['namespaces'], data['items']
    for ini in INITIATIVES:
        pid = ini['id']
        prefix = prefixes.setdefault(pid, f"ORG-{ini['slug'].upper()}")
        high = max((int(row['key'].rsplit('-', 1)[1]) for row in items.values() if row['projectId'] == pid), default=0)
        for ekey, _title, _priority, _status, _description, children in ini['epics']:
            ids = [f"wi-{ini['slug']}-{ekey}"] + [
                f"wi-{ini['slug']}-{ekey}-{'b' if child[0] == 'bug' else 's'}{n}"
                for n, child in enumerate(children, 1)
            ]
            for item_id in ids:
                if item_id not in items:
                    high += 1
                    items[item_id] = {'projectId': pid, 'key': f'{prefix}-{high}'}
    if len(set(prefixes.values())) != len(prefixes):
        raise ValueError('Work-key namespaces must be unique')
    seen = set()
    for item_id, row in items.items():
        key = row['key']
        prefix = prefixes[row['projectId']]
        if not re.fullmatch(re.escape(prefix) + r'-[1-9][0-9]*', key) or key in seen:
            raise ValueError(f'Invalid or duplicate key: {item_id}: {key}')
        seen.add(key)
    registry = json.dumps(data, indent=2) + '\n'
    runtime = '// Generated by schema/seeds/generate_work_item_keys.py. Change the registry, not this file.\n'
    runtime += 'export const WORK_KEY_PREFIXES: Readonly<Record<string, string>> = ' + json.dumps(prefixes, indent=2) + ';\n'
    runtime += 'export const SEEDED_WORK_KEYS: Readonly<Record<string, string>> = ' + json.dumps({i: row['key'] for i, row in items.items()}, indent=2) + ';\n'
    namespace_rows = []
    for pid, prefix in prefixes.items():
        high = max((int(row['key'].rsplit('-', 1)[1]) for row in items.values() if row['projectId'] == pid), default=0)
        namespace_rows.append(f"  ('{pid}', '{prefix}', {high + 1})")
    seed_rows = [f"  ('{i}', '{row['projectId']}', '{row['key']}')" for i, row in items.items()]
    migration = TEMPLATE.read_text().replace('{{NAMESPACES}}', ',\n'.join(namespace_rows)).replace('{{SEED_KEYS}}', ',\n'.join(seed_rows))
    return {REGISTRY: registry, RUNTIME: runtime, MIGRATION: migration}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, body in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != body:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(body)
    if stale:
        raise SystemExit('Regenerate work keys: ' + ', '.join(stale))
    print('Work-key registry and migration are current.' if args.check else 'Generated work-key registry, runtime map and migration.')
