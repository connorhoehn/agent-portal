#!/usr/bin/env bash
# Apply work-items schema + full seed to Aurora via RDS Data API.
# Run AFTER the main schema and seed have been applied.
# Safe to re-run — all inserts use ON CONFLICT (id) DO NOTHING.
set -euo pipefail

REGION="${AWS_DEFAULT_REGION:-us-east-1}"

AURORA_CLUSTER_ARN=$(aws cloudformation describe-stacks \
  --stack-name OrgIQ-Aurora --region "$REGION" \
  --query "Stacks[0].Outputs[?OutputKey=='ClusterArn'].OutputValue" \
  --output text)
AURORA_SECRET_ARN=$(aws cloudformation describe-stacks \
  --stack-name OrgIQ-Aurora --region "$REGION" \
  --query "Stacks[0].Outputs[?OutputKey=='CredentialsSecretArn'].OutputValue" \
  --output text)

SCHEMA_FILE="$(dirname "$0")/orgiq_work_items_schema.sql"
KEY_SCHEMA_FILE="$(dirname "$0")/work_item_key_schema.sql"
PROGRAM_SCHEMA_FILE="$(dirname "$0")/program_schema.sql"
# The curated program seed: 14 canonical p-* initiatives, each with one owner,
# a couple of SMEs, epics/stories/bugs estimated in points and dollars,
# sprints, SME budget grants, and maintenance bots with run history.
# Generated by seeds/generate_program_seed.py — regenerate, don't hand-edit.
SEED_FILE="$(dirname "$0")/seed_program.sql"

echo "Aurora cluster : $AURORA_CLUSTER_ARN"
echo "Secret         : $AURORA_SECRET_ARN"
echo ""

run_file() {
  local file="$1"
  local label="$2"
  echo "Applying $label ($file)..."
  local count=0

  # Preserve dollar-quoted function bodies and SQL newlines. JSON encoding
  # carries each complete statement through the line-oriented shell loop.
  while IFS= read -r encoded; do
    stmt="$(python3 -c 'import json,sys; print(json.loads(sys.argv[1]))' "$encoded")"
    [ -z "$stmt" ] && continue
    count=$((count + 1))
    preview="$(echo "$stmt" | head -c 80)"
    echo "  [$count] ${preview}..."
    aws rds-data execute-statement \
      --resource-arn "$AURORA_CLUSTER_ARN" \
      --secret-arn   "$AURORA_SECRET_ARN" \
      --database orgiq \
      --region "$REGION" \
      --sql "$stmt" \
      --output json > /dev/null
  done < <(python3 - "$file" <<'PYEOF'
import json, re, sys
current, tag = [], None
for line in open(sys.argv[1]):
    stripped = line.strip()
    if tag is None and (not stripped or stripped.startswith('--')):
        continue
    current.append(line)
    for marker in re.findall(r'\$[A-Za-z_][A-Za-z0-9_]*\$|\$\$', line):
        if tag is None:
            tag = marker
        elif marker == tag:
            tag = None
    if tag is None and stripped.endswith(';'):
        print(json.dumps(''.join(current).strip()))
        current = []
if tag is not None or ''.join(current).strip():
    raise SystemExit('Incomplete SQL statement')
PYEOF
  )

  echo "  Done: $count statements."
}

run_file "$SCHEMA_FILE"         "work-items schema"
run_file "$KEY_SCHEMA_FILE"     "immutable work-item keys"
run_file "$PROGRAM_SCHEMA_FILE" "program schema (sprints, grants, estimates)"
run_file "$SEED_FILE"           "curated program seed"

echo ""
echo "Verifying row counts..."
for tbl in work_items work_item_comments sprints budget_grants bots bot_runs; do
  cnt=$(aws rds-data execute-statement \
    --resource-arn "$AURORA_CLUSTER_ARN" \
    --secret-arn   "$AURORA_SECRET_ARN" \
    --database orgiq \
    --region "$REGION" \
    --sql "SELECT COUNT(*) FROM $tbl" \
    --query "records[0][0].longValue" --output text)
  printf "  %-20s %s rows\n" "$tbl" "$cnt"
done
echo ""
echo "Done."
